ma_dt = int(input("Nhap vao ma dan toc (1-5): "))
if ma_dt == 1:
    print("Kinh")
elif ma_dt == 2:
    print("Tay")
elif ma_dt == 3:
    print("Nung")
elif ma_dt == 4:
    print("Thai")
elif ma_dt == 5:
    print("Kh-mer")
else:
    print("Ma dan toc khong hop le")
